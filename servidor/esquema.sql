CREATE TABLE IF NOT EXISTS mediciones (
    registro_id INTEGER PRIMARY KEY AUTOINCREMENT,
    id INTEGER NOT NULL CHECK (id BETWEEN 1 AND 5),
    mp01 INTEGER NOT NULL,
    mp02 INTEGER NOT NULL,
    mp03 INTEGER NOT NULL,
    hi01 INTEGER NOT NULL,
    hi02 INTEGER NOT NULL,
    hi03 INTEGER NOT NULL,
    hi04 INTEGER NOT NULL,
    hi05 INTEGER NOT NULL,
    hi06 INTEGER NOT NULL,
    te INTEGER NOT NULL,
    hr INTEGER NOT NULL CHECK (hr BETWEEN 0 AND 100),
    fecha_hora DATETIME NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_mediciones_uma_registro
ON mediciones (id, registro_id);
